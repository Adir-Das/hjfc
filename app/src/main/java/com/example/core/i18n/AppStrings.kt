enum class AppLanguage(val code: String, val displayLabel: String) {
    BENGALI("bn", "বাংলা"),
    ENGLISH("en", "English");

    companion object {
        fun fromCode(code: String?): AppLanguage =
            entries.firstOrNull { it.code.equals(code, ignoreCase = true) } ?: BENGALI
    }
}

object Formatters {
    fun formatBdt(amount: Double): String {
        val nf = NumberFormat.getNumberInstance(Locale("en", "BD")).apply {
            minimumFractionDigits = if (amount % 1.0 == 0.0) 0 else 2
            maximumFractionDigits = 2
        }
        return "৳ ${nf.format(amount)}"
    }

    fun todayDhaka(): LocalDate = ZonedDateTime.now(AppConfig.DHAKA_ZONE).toLocalDate()

    fun nowDhakaIso(): String = ZonedDateTime.now(AppConfig.DHAKA_ZONE).format(DateTimeFormatter.ISO_OFFSET_DATE_TIME)

    fun formatDateDisplay(dateStr: String): String {
        return runCatching {
            val d = LocalDate.parse(dateStr.take(10))
            d.format(DateTimeFormatter.ofPattern("dd MMM yyyy"))
        }.getOrDefault(dateStr)
    }
}

